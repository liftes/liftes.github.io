// Run from any directory: node Photo/scripts/update-photos.cjs
// Only updates Photo/data/photos.js. Original images are never changed.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const folders = { recent:'img-Norfe/Recent', single:'SubSites/single', double:'SubSites/double', more:'SubSites/more' };
function scan(folder) {
  const absolute = path.join(root, folder);
  if (!fs.existsSync(absolute)) throw new Error('Missing gallery folder: ' + folder);
  return fs.readdirSync(absolute, {withFileTypes:true}).flatMap(entry => {
    const relative = folder + '/' + entry.name;
    if (entry.isDirectory()) return scan(relative);
    return entry.isFile() && /\.(jpe?g|png|webp|avif|gif)$/i.test(entry.name) ? [{path:relative}] : [];
  });
}
const manifest = Object.fromEntries(Object.entries(folders).map(([key, folder]) => [
  key, scan(folder).sort((a,b) => a.path.localeCompare(b.path, 'en', {numeric:true}))
]));
const albums = JSON.parse(fs.readFileSync(path.join(root, 'data', 'albums.json'), 'utf8'));
for (const [key, album] of Object.entries(albums)) {
  const listed = (album.images || []).map(relative => {
    const absolute = path.resolve(root, relative);
    if (!absolute.startsWith(root + path.sep) || !fs.existsSync(absolute)) throw new Error('Invalid album image: ' + relative);
    return {path:relative};
  });
  const extra = fs.existsSync(path.join(root, album.folder)) ? scan(album.folder).sort((a,b) => a.path.localeCompare(b.path,'en',{numeric:true})) : [];
  manifest[key] = [...new Map([...listed, ...extra].map(photo => [photo.path, photo])).values()];
}
fs.mkdirSync(path.join(root,'data'), {recursive:true});
fs.writeFileSync(path.join(root,'data','photos.js'), '// Generated by scripts/update-photos.cjs; do not edit by hand.\nwindow.PHOTO_MANIFEST = ' + JSON.stringify(manifest,null,2) + ';\n', 'utf8');
for (const [key, photos] of Object.entries(manifest)) console.log(key + ': ' + photos.length + ' photos');
